    public double getAngle(double meters)
    {
        double pi = Math.PI;
        double g = 9.808;
        double h = 1.45;
        double v_iy = Math.sqrt(2 * g * h);
        double t = v_iy / g;
        double v_ix = meters / t;
        double v_i = Math.sqrt(Math.pow(v_ix,2) + Math.pow(v_iy,2));
        return Math.asin(v_iy / v_i) * 57.2958; //angle of launch
    }

